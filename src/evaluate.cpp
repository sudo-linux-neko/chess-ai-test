int evaluate_hce(const Position& pos) {
  int mg = 0, eg = 0, phase = 0;
  for (int sq = 0; sq < 64; ++sq) {
    Piece p = pos.piece_on(sq);
    if (p == Piece::None) continue;
    PieceType t = type_of(p);
    Color c = color_of(p);
    int s = (c == Color::White) ? 1 : -1;
    int idx = (c == Color::White) ? sq : flip(sq);
    mg += s * (kMatMG[(int)t] + kPstMG[(int)t][idx]);
    eg += s * (kMatEG[(int)t] + kPstEG[(int)t][idx]);
    if (t != PieceType::Pawn && t != PieceType::King)
      phase += (t == PieceType::Knight || t == PieceType::Bishop) ? 1
               : (t == PieceType::Rook) ? 2 : 4;
  }
  if (phase > 24) phase = 24;
  return (mg * phase + eg * (24 - phase)) / 24;
}

// External NNUE instance is owned by UCI/search; default null => HCE.
namespace { NNUE* g_nnue = nullptr; }
void chessclaw_set_nnue(NNUE* n) { g_nnue = n; }

int evaluate(const Position& pos) {
  int v;
  if (g_nnue && g_nnue->loaded)
    v = g_nnue->infer(pos);
  else
    v = evaluate_hce(pos);
  return pos.side_to_move() == Color::White ? v : -v;
}

